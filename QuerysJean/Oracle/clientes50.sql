AND CLFCNA >= 19700101 AND NOT EXISTS (SELECT * FROM T_AHMAEST WHERE MSCDCL = CLKEY)
AND NOT EXISTS (SELECT * FROM T_MAESTRO WHERE MTCODCLT = CLKEY) 



