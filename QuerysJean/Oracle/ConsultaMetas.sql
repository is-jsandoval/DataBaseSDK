--CONSULTA DE METAS
SELECT *
FROM BG_ADMIN.T_AHKSLAM
WHERE AHKSLAM_STATUS    = 'A' --A- ACTIVO, C - CANCELADO, E- ELIMINADO
and  AHKSLAM_CUENTA_MULT = 15496350    --CUENTA DE AHORRO DE LA META
AND AHKSLAM_VALOR_ACUM > 100           --VALOR ACUMULADO
--AHKSLAM_MARCA_PRECANCELA   Indica si se precancela = P


--CONSULTA REGISTRO DE APORTES / RETIROS
SELECT *
from bg_admin.t_AHKMETA
where AHMT_CTA  = '15496350'
AND AHMT_SOLIC = 9100375
and AHMT_FECHA > 20240801
order by AHMT_FECHA desc

