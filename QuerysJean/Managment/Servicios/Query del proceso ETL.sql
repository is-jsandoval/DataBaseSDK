SELECT 
	CLT.CLCDID,
    A.SOKDODT_CLIENTE,
 
	CASE 
		WHEN B.SOKDODG_FECHA_CONC <> 0
		THEN CONVERT(date, CONVERT(char(8), B.SOKDODG_FECHA_CONC), 112)
		ELSE NULL
	END AS SOKDODG_FECHA_CONC,
 
	CASE 
		WHEN A.SOKDODT_FECHA_VCTO <> 0
		THEN CONVERT(date, CONVERT(char(8), A.SOKDODT_FECHA_VCTO), 112)
		ELSE NULL
	END AS SOKDODT_FECHA_VCTO,
 
 
    A.SOKDODT_NUMERO_DOC,
    A.SOKDODT_ESTATUS,
    A.SOKDODT_TIPO,
 
	CASE 
		WHEN A.SOKDODT_FECHA_CANC <> 0
		THEN CONVERT(date, CONVERT(char(8), A.SOKDODT_FECHA_CANC), 112)
		ELSE NULL
	END AS SOKDODT_FECHA_CANC,
 
    A.SOKDODT_CAPITAL,
    A.SOKDODT_PAG_CAPITAL,
    A.SOKDODT_INTERES,
    A.SOKDODT_PAG_INTERES,
    B.SOKDODG_PLAZO_DIAS,
    B.SOKDODG_TIPO_CTA,
    B.SOKDODG_NUMERO_CTA,
    M.SOKMOVI_IND_DOCU,
 
	CASE 
		WHEN M.SOKMOVI_FECHA_MOVI <> 0
		THEN CONVERT(date, CONVERT(char(8), M.SOKMOVI_FECHA_MOVI), 112)
		ELSE NULL
	END AS SOKMOVI_FECHA_MOVI,
    M.SOKMOVI_INDICE_MOVI,
    M.SOKMOVI_FORMA_PAG,
    M.SOKMOVI_CAPITAL,
    M.SOKMOVI_INTERES
 
FROM dbo.SOKDODT_DIARIO A
INNER JOIN dbo.SOKDODG_DIARIO B
    ON B.SOKDODG_CLIENTE = A.SOKDODT_CLIENTE
   AND B.SOKDODG_FECHA_CONC = A.SOKDODT_FECHA_CONC
   AND B.SOKDODG_KEY_INDICE = A.SOKDODT_KEY_INDICE_2
   AND A.SOKDODT_TIPO = 'CZ'
 
INNER JOIN dbo.SOKMOVI_DIARIO M
    ON M.SOKMOVI_CLIENTE = A.SOKDODT_CLIENTE
   AND M.SOKMOVI_FECVCTO = A.SOKDODT_FECHA_VCTO
   
 
INNER JOIN dbo.CLTEFIL_DIARIO CLT
    ON A.SOKDODT_CLIENTE = CLT.clkey